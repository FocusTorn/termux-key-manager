import json
import os

from config import BASHRC_PATH, HELPERS_PATH, JSON_PATH


BASHRC_START = "# >>> termux-key-manager history >>>"
BASHRC_END = "# <<< termux-key-manager history <<<"


def get_shell_commands():

    with open(
        JSON_PATH,
        "r",
        encoding="utf-8"
    ) as f:

        data = json.load(f)

    commands = []

    for definition in data.get("definitions", {}).values():

        shell = definition.get("shell")

        if shell:
            commands.append(shell)

        popup = definition.get("popup")

        if isinstance(popup, dict):

            shell = popup.get("shell")

            if shell:
                commands.append(shell)

    return list(dict.fromkeys(commands))


def update_bashrc(shell_commands):

    histignore = ":".join(
        "cpy*" if command == "cpy" else command
        for command in shell_commands
    )

    block = f'''{BASHRC_START}
# Auto-generated by ~/projects/termux-key-manager/update.py
# Do not edit this section manually.

export HISTIGNORE='{histignore}'

if [ -f "$HOME/.termux/helpers.sh" ]; then
    . "$HOME/.termux/helpers.sh"
fi

{BASHRC_END}'''

    if os.path.exists(BASHRC_PATH):

        with open(
            BASHRC_PATH,
            "r",
            encoding="utf-8"
        ) as f:

            bashrc = f.read()

    else:

        bashrc = ""

    start = bashrc.find(BASHRC_START)
    end = bashrc.find(BASHRC_END)

    if start != -1 and end != -1:

        end += len(BASHRC_END)

        bashrc = (
            bashrc[:start]
            + block
            + bashrc[end:]
        )

    else:

        if bashrc and not bashrc.endswith("\n"):
            bashrc += "\n"

        bashrc += "\n" + block + "\n"

    with open(
        BASHRC_PATH,
        "w",
        encoding="utf-8"
    ) as f:

        f.write(bashrc)


def generate_helpers():

    shell_commands = get_shell_commands()

    histignore = ":".join(
        "cpy*" if command == "cpy" else command
        for command in shell_commands
    )

    helpers = f'''# ===========================================
# AUTO-GENERATED BY ~/projects/termux-key-manager/update.py
#
# DO NOT EDIT THIS FILE MANUALLY.
#
# Source of truth:
#     ~/projects/termux-key-manager/macros.jsonc
# ===========================================


export HISTIGNORE='{histignore}'

TMK_SESSION_DIR="$HOME/.termux/tmk-session"
TMK_SESSION_RECORDS="$TMK_SESSION_DIR/records"

mkdir -p "$TMK_SESSION_RECORDS"


_tmk_recorder_debug()
{{
    [[ "$TMK_SESSION_INITIALIZING" == 1 ]] && return
    [[ "$TMK_HELPER_ACTIVE" == 1 ]] && return

    case "$BASH_COMMAND" in
        _tmk_*|TMK_HELPER_ACTIVE=*|cpy_new*|refresh|clr|exit)
            return
            ;;
    esac

    if [[ "$TMK_SESSION_ACTIVE" != 1 ]]; then
        TMK_SESSION_ACTIVE=1
        TMK_SESSION_COMMANDS=
        TMK_SESSION_OUT="$TMK_SESSION_DIR/current.$$"

        : > "$TMK_SESSION_OUT"

        exec 9>&1
        exec 8>&2

        exec > >(tee -a "$TMK_SESSION_OUT" >&9) 2>&1
    fi

    if [[ -n "$TMK_SESSION_COMMANDS" ]]; then
        TMK_SESSION_COMMANDS+=$'\\n'
    fi

    TMK_SESSION_COMMANDS+="$BASH_COMMAND"
}}


_tmk_recorder_prompt()
{{
    local status=$?
    local hist_line hist_id

    if [[ "$TMK_SESSION_ACTIVE" == 1 ]]; then

        exec 1>&9
        exec 2>&8

        exec 9>&-
        exec 8>&-

        hist_line="$(history 1)"
        hist_line="${{hist_line#"${{hist_line%%[![:space:]]*}}"}}"
        read -r hist_id _ <<< "$hist_line"

        if [[ -z "$hist_id" ]]; then
            hist_id="$$"
        fi

        mv "$TMK_SESSION_OUT"            "$TMK_SESSION_RECORDS/$hist_id"

        printf '%s
' "$TMK_SESSION_COMMANDS"             > "$TMK_SESSION_RECORDS/$hist_id.cmd"

        TMK_SESSION_ACTIVE=0
        TMK_SESSION_COMMANDS=
        TMK_SESSION_OUT=
    fi

    return "$status"
}}


_tmk_recorder_install()
{{
    TMK_HELPER_ACTIVE=1

    trap '_tmk_recorder_debug' DEBUG

    # Remove any previous recorder hook before installing exactly one.
    while [[ "$PROMPT_COMMAND" == *"_tmk_recorder_prompt"* ]]; do
        PROMPT_COMMAND="${{PROMPT_COMMAND//_tmk_recorder_prompt;/}}"
        PROMPT_COMMAND="${{PROMPT_COMMAND//;_tmk_recorder_prompt/}}"
        PROMPT_COMMAND="${{PROMPT_COMMAND//_tmk_recorder_prompt/}}"
    done

    if [[ -n "$PROMPT_COMMAND" ]]; then
        PROMPT_COMMAND="_tmk_recorder_prompt;$PROMPT_COMMAND"
    else
        PROMPT_COMMAND="_tmk_recorder_prompt"
    fi

    TMK_HELPER_ACTIVE=0
}}


TMK_SESSION_ACTIVE=0
TMK_SESSION_COMMANDS=
TMK_SESSION_OUT=
TMK_SESSION_INITIALIZING=1
TMK_HELPER_ACTIVE=0

_tmk_recorder_install

TMK_SESSION_INITIALIZING=0


_tmk_is_helper() {{

    case "$1" in
        cpy|cpy\\ *|cpy_all|cpy_out|cpy_out\\ *|refresh|clr)
            return 0
            ;;
        *)
            return 1
            ;;
    esac
}}


_tmk_capture_output() {{

    local current_command

    current_command="$(fc -ln -1 2>/dev/null)"

    if _tmk_is_helper "$current_command"; then
        return
    fi

    TMK_LAST_OUTPUT="$(tmux capture-pane -p 2>/dev/null)"
    export TMK_LAST_OUTPUT
}}


_tmk_install_prompt_hook() {{

    case ";${{PROMPT_COMMAND:-}};" in

        *";_tmk_capture_output;"*)
            ;;

        *)
            if [ -n "${{PROMPT_COMMAND:-}}" ]; then
                PROMPT_COMMAND="_tmk_capture_output;$PROMPT_COMMAND"
            else
                PROMPT_COMMAND="_tmk_capture_output"
            fi
            ;;

    esac
}}


refresh() {{

    if python "$HOME/projects/termux-key-manager/update.py"; then

        . "$HOME/.termux/helpers.sh"

        if [ -n "$TMUX" ]; then
            tmux set-environment -g HISTIGNORE "$HISTIGNORE"
        fi

    fi
    source ~/.bashrc
}}


cpy() {{
    TMK_HELPER_ACTIVE=1

    case "$1" in
        all)
            cpy_new all
            ;;
        out)
            cpy_new out
            ;;
        rec)
            cpy_new rec
            ;;
        *)
            printf '%s\\n' \
                'Usage: cpy {{all|out|rec}}' >&2
            TMK_HELPER_ACTIVE=0
            return 2
            ;;
    esac

    TMK_HELPER_ACTIVE=0
}}


cpy_all() {{

    tmux capture-pane -pS - |
        sed 's/cpy_all$//' |
        sed ':a;/^[[:space:]]*$/{{$d;N;ba;}}' |
        termux-clipboard-set
}}


_tmk_session_latest()
{{
    local latest

    latest="$(
        find "$TMK_SESSION_RECORDS"             -maxdepth 1             -type f             ! -name '*.cmd'             -printf '%f\\n' |
            sort -n |
            tail -n 1
    )"

    [[ -n "$latest" ]] || return 1

    printf '%s\\n' "$latest"
}}


cpy_new()
{{
    local mode="$1"
    local latest id
    local cmd_file out_file

    case "$mode" in

        all)
            for out_file in "$TMK_SESSION_RECORDS"/*; do

                [[ -f "$out_file" ]] || continue
                [[ "$out_file" == *.cmd ]] && continue

                id="${{out_file##*/}}"
                cmd_file="$TMK_SESSION_RECORDS/$id.cmd"

                [[ -f "$cmd_file" ]] || continue

                cat "$cmd_file"
                printf '\\n'

                cat "$out_file"
                printf '\\n'
            done |
            termux-clipboard-set
            ;;

        out)
            latest="$(_tmk_session_latest)" || return 1
            cat "$TMK_SESSION_RECORDS/$latest" |
                termux-clipboard-set
            ;;

        rec)
            latest="$(_tmk_session_latest)" || return 1
            cmd_file="$TMK_SESSION_RECORDS/$latest.cmd"
            out_file="$TMK_SESSION_RECORDS/$latest"

            {{
                cat "$cmd_file"
                printf '\\n'
                cat "$out_file"
            }} |
            termux-clipboard-set
            ;;

        *)
            printf '%s\\n'                 'Usage: cpy_new {{all|out|rec}}' >&2
            return 2
            ;;
    esac
}}


clr() {{
    TMK_HELPER_ACTIVE=1

    # Clear authoritative structured session data.
    find "$TMK_SESSION_RECORDS"         -maxdepth 1         -type f         -delete

    # Remove any abandoned in-progress capture.
    find "$TMK_SESSION_DIR"         -maxdepth 1         -type f         -name 'current.*'         -delete

    if [ -n "$TMUX" ]; then
        tmux send-keys -t "$TMUX_PANE" C-c
        tmux send-keys -t "$TMUX_PANE" -R
        tmux clear-history
    else
        printf '\\003'
        printf '\\033c'
        clear
    fi

    TMK_HELPER_ACTIVE=0
}}


_tmk_install_prompt_hook


'''

    with open(
        HELPERS_PATH,
        "w",
        encoding="utf-8"
    ) as f:

        f.write(helpers)

    os.chmod(
        HELPERS_PATH,
        0o700
    )

    update_bashrc(shell_commands)


if __name__ == "__main__":
    generate_helpers()
