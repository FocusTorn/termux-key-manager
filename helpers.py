try:
    old_marker = lines.index("--- old\\n")
    new_marker = lines.index("--- new\\n")
except ValueError:
    print("FAIL: edit specification requires --- old and --- new", file=sys.stderr)
    raise SystemExit(1)

if old_marker != 0:
    print("FAIL: edit specification must begin with --- old", file=sys.stderr)
    raise SystemExit(1)

